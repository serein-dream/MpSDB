def run(verbose=False, dummy=False):
    seeds = np.random.choice(range(10000000), size=30, replace=False)
    # seeds = range(NUM_SEEDS)
    NUM_CLUSTERS = 5
    LIMIT_CSV = None
    EPOCHS = 5
    ROUNDS = 100
    use_metric = "davies_bouldin"  # "euclidean",  "davies_bouldin" "silhouette"
    init_centroids = "random"  # "random "GMM"
    LR = 0.5
    LR_AD = None
    EPOCH_LR = 0.5
    MOMENTUM = 0.5
    # RECORD = range(1, ROUNDS+1)
    RECORD = None
    REASSIGN = (0.01, 10)
    stats = {
        'train': {'avg': [], 'std': []},
        'test': {'avg': [], 'std': []},
    }
    num_s = 10 #对应num_seeds和clients_per_round_fractions
    C = 0.10
    print("clients_per_round_fraction", C)
    splits = ['train', 'test']
    results = {}
    for split in splits:
        results[split] = []
    for SEED in seeds[:num_s]:
        np.random.seed(seed=SEED)
        if verbose:
            print("seed", SEED)
        x, _ = load_federated(
            limit_csv=LIMIT_CSV,
            verbose=verbose,
            seed=SEED,
            dummy=dummy,
            clusters=NUM_CLUSTERS,
        )
        if dummy:
            centroids = "random"
        else:
            centroids = init_centroids_gmm(
                init_centroids=init_centroids,
                num_clusters=NUM_CLUSTERS,
                seed=SEED,
                dims=x['train'][0].shape[1],
                verbose=verbose,
            )


        kmeans = KMeansFederated(
            n_clusters=NUM_CLUSTERS,
            # batch_size=BATCH_SIZE,
            sample_fraction=C,  #??
            epochs_per_round=EPOCHS,
            max_iter=ROUNDS,
            init_centroids=centroids,
            seed=SEED,
            learning_rate=LR,
            adaptive_lr=LR_AD,
            epoch_lr=EPOCH_LR,
            momentum=MOMENTUM,  #??
            reassign_min=REASSIGN[0], #??
            reassign_after=REASSIGN[1],
        )

        if verbose:
            print(vars(kmeans))

        #下面应该是一次完整的联邦
        kmeans.fit(
            X=x['train'],
            record_at=RECORD,
        )
        
        scores = evaluate(
            kmeans=kmeans,
            x=x,
            splits=splits,
            use_metric=use_metric,
            federated=(C != "central"),
            verbose=verbose,
        )
        for key, value in scores.items():
            results[key].append(value)
        if verbose:
            print(use_metric, scores)
    results_avg = {}
    for key, value in results.items():
        score_mean = np.around(np.mean(value), decimals=3)
        score_std = np.around(np.std(value), decimals=3)
        results_avg[key] = (score_mean, score_std)
        stats[key]['avg'].append(score_mean)
        stats[key]['std'].append(score_std)
    print(use_metric, results_avg)





if __name__ == '__main__':
    run(
        dummy=True,
        verbose=False,
    )
